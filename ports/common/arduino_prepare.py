"""Shared part of the prepare.py scripts of the Arduino-based ports
(ports/ttgo-vga32, ports/esp32-cyd): fills <sketch>/src/gen/ with one small
.cpp/.c per dsp source of the chosen drivers (each just #includes the file
from the repository, so nothing is copied), the port core, zlib, the generated
dsp_drivers.h and dsp_port_config.h and, optionally, the embedded media.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys

COMMON = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(COMMON))
# Never built for a board: Model 3 needs threads and C++ exceptions, the
# Macintosh II's 68020 core (Musashi) ~850 KB of tables in RAM.
UNSUPPORTED = ["model3", "macii"]
ZLIB_FILES = ["adler32", "compress", "crc32", "deflate", "inffast", "inflate", "inftrees", "trees",
              "uncompr", "zutil"]


def driver_groups():
    with open(os.path.join(REPO, "cmake", "drivers.cmake")) as f:
        text = f.read()
    groups = {}
    for group in ("ARCADE", "CONSOLES", "COMPUTERS"):
        m = re.search(r"set\(DSP_DRIVERS_%s\s+(.*?)\)" % group, text, re.S)
        groups[group.lower()] = m.group(1).split()
    return groups


def resolve(spec):
    groups = driver_groups()
    every = groups["arcade"] + groups["consoles"] + groups["computers"]
    aliases = {"all": every, "arcade": groups["arcade"], "consoles": groups["consoles"],
               "console": groups["consoles"], "computers": groups["computers"],
               "computer": groups["computers"]}
    out = []
    for item in re.split(r"[;,\s]+", spec):
        item = item.strip().lower()
        if not item:
            continue
        if item in UNSUPPORTED:
            sys.exit(f"prepare: the {item} driver is not supported on microcontrollers")
        names = [n for n in aliases.get(item, [item]) if n not in UNSUPPORTED]
        for n in names:
            if n not in every:
                sys.exit(f"prepare: unknown driver '{n}'. Valid names: {' '.join(every)}")
            if n not in out:
                out.append(n)
    if not out:
        sys.exit("prepare: no drivers chosen")
    return out


def include_dirs(gen, zlib_dir):
    return [gen, os.path.join(REPO, "src"), os.path.join(REPO, "src", "cpu", "musashi"), COMMON, zlib_dir]


def wrapper(gen, target, index):
    base = os.path.basename(target)
    stem, ext = os.path.splitext(base)
    name = f"dsp_{index:03d}_{re.sub(r'[^A-Za-z0-9_]', '_', stem)}{'.c' if ext == '.c' else '.cpp'}"
    rel = os.path.relpath(target, gen).replace(os.sep, "/")
    with open(os.path.join(gen, name), "w", newline="\n") as f:
        f.write(f"// Generated by prepare.py: compiles {os.path.relpath(target, REPO)}.\n")
        f.write(f'#include "{rel}"\n')


def main(port_dir, sketch, title, default_drivers, add_options=None, config=None, extra=()):
    """Command line of a port's prepare.py. `add_options(parser)` adds the
    port's own options; `config(args)` returns the lines of dsp_port_config.h;
    `extra` names more files of ports/common to compile (e.g. esp32_support.cpp)."""
    gen = os.path.join(port_dir, sketch, "src", "gen")
    p = argparse.ArgumentParser(description=sys.modules["__main__"].__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--drivers", default=default_drivers,
                   help=f"drivers or groups, ';' separated (default: {default_drivers})")
    p.add_argument("--zlib", default=os.path.join(port_dir, "deps", "zlib"), help="zlib source tree (setup.sh)")
    p.add_argument("--embed-game")
    p.add_argument("--embed-rom")
    p.add_argument("--embed-tape", action="append", default=[])
    p.add_argument("--embed-disk", action="append", default=[])
    p.add_argument("--embed-cart", action="append", default=[])
    p.add_argument("--embed-arg", action="append", default=[])
    if add_options:
        add_options(p)
    p.add_argument("--print-flags", action="store_true", help="print the -I flags and exit")
    args = p.parse_args()
    zlib_dir = os.path.abspath(args.zlib)
    if args.print_flags:
        print(" ".join(f"-I{d}" for d in include_dirs(gen, zlib_dir)))
        return args
    if not os.path.isfile(os.path.join(zlib_dir, "inflate.c")):
        sys.exit(f"prepare: zlib not found in {zlib_dir} (run setup.sh)")

    drivers = resolve(args.drivers)
    with open(os.path.join(COMMON, "driver_sources.json")) as f:
        table = json.load(f)
    sources = list(table["core"]) + ["src/frontend/machine_registry.cpp"]
    for d in drivers:
        if d not in table["drivers"]:
            sys.exit(f"prepare: {d} missing from ports/common/driver_sources.json (run tools/driver_sources.py)")
        for s in table["drivers"][d]["sources"]:
            if s not in sources:
                sources.append(s)

    if os.path.isdir(gen):
        shutil.rmtree(gen)
    os.makedirs(gen)
    targets = [os.path.join(REPO, s) for s in sources]
    targets += [os.path.join(COMMON, "port_core.cpp"), os.path.join(COMMON, "memfs.cpp")]
    targets += [os.path.join(COMMON, e) for e in extra]
    targets += [os.path.join(zlib_dir, z + ".c") for z in ZLIB_FILES]
    if args.embed_rom:
        if not args.embed_game:
            sys.exit("prepare: --embed-rom needs --embed-game")
        cmd = [sys.executable, os.path.join(REPO, "tools", "embed_media.py"), "-o",
               os.path.join(gen, "embedded_media.c"), "--game", args.embed_game, "--rom", args.embed_rom]
        for kind in ("tape", "disk", "cart"):
            for f in getattr(args, f"embed_{kind}"):
                cmd += [f"--{kind}", f]
        cmd += [f"--arg={a}" for a in args.embed_arg]
        subprocess.run(cmd, check=True)
    else:
        targets.append(os.path.join(REPO, "src", "core", "embedded_media_none.c"))
    for i, t in enumerate(targets):
        wrapper(gen, t, i)

    with open(os.path.join(gen, "dsp_drivers.h"), "w", newline="\n") as f:
        f.write(f"// Generated by prepare.py: drivers built into the {title} firmware.\n#pragma once\n")
        for d in drivers:
            f.write(f"#define DSP_DRIVER_{re.sub(r'[^A-Z0-9_]', '_', d.upper())} 1\n")
    with open(os.path.join(gen, "dsp_port_config.h"), "w", newline="\n") as f:
        f.write("// Generated by prepare.py.\n#pragma once\n")
        for line in (config(args) if config else []):
            f.write(line + "\n")
    print(f"prepare: {len(drivers)} driver(s) ({' '.join(drivers)}), {len(sources)} dsp source files"
          f"{', embedded ' + args.embed_game if args.embed_rom else ''} -> {os.path.relpath(gen, port_dir)}")
    return args
