void OpWolfCChip::reset() {
    ram_.fill(0);
    current_cmd_ = 0;
    current_bank_ = 0;
    last_7a_ = 0;
    last_04_ = 0xfc;
    last_05_ = 0xff;
    c588_ = 0;
    c589_ = 0;
    c58a_ = 0;
    coins_.fill(0);
    coins_for_credit_.fill(1);
    credits_for_coin_.fill(1);
    command_cycles_ = -1;
}

void OpWolfCChip::set_rom(const uint16_t* rom, size_t words) {
    rom_ = rom;
    rom_words_ = words;
}

void OpWolfCChip::set_inputs(uint8_t in0, uint8_t in1) {
    ram_[0x04] = in0;
    ram_[0x05] = in1;
}

uint16_t OpWolfCChip::data_r(uint16_t address) const {
    address = uint16_t(address >> 1);
    return ram_[size_t(current_bank_) * 0x400 + address];
}

void OpWolfCChip::apply_coinage(uint8_t dsw_a) {
    if (rom_ == nullptr) return;
    const uint32_t tables[2] = {0x03ffde, 0x03ffee};
    const int offsets[2] = {12 - 4 * ((dsw_a & 0x30) >> 4), 12 - 4 * ((dsw_a & 0xc0) >> 6)};
    for (int slot = 0; slot < 2; slot++) {
        size_t credit_index = size_t((tables[slot] + uint32_t(offsets[slot])) >> 1);
        size_t coin_index = size_t((tables[slot] + uint32_t(offsets[slot]) + 2) >> 1);
        if (credit_index < rom_words_) coins_for_credit_[size_t(slot)] = uint8_t(rom_[credit_index] & 0xff);
        if (coin_index < rom_words_) credits_for_coin_[size_t(slot)] = uint8_t(rom_[coin_index] & 0xff);
    }
}

void OpWolfCChip::data_w(uint16_t address, uint16_t value) {
    address = uint16_t(address >> 1);
    ram_[size_t(current_bank_) * 0x400 + address] = uint8_t(value & 0xff);
    if (current_bank_ != 0) return;
    if (address == 0x14) apply_coinage(uint8_t(value & 0xff));
    if (address == 0x15) update_difficulty(0);
}

void OpWolfCChip::status_w(uint16_t value) {
    (void)value;
    ram_[0x3d] = 1;
    ram_[0x7a] = 1;
    update_difficulty(0);
}

void OpWolfCChip::bank_w(uint16_t value) { current_bank_ = uint8_t(value & 7); }

void OpWolfCChip::update_difficulty(uint8_t mode) {
    const uint8_t dip = uint8_t(ram_[0x15] & 3);
    if (mode == 0) {
        switch (dip) {
            case 3:
                ram_[0x2c] = 0x31;
                ram_[0x77] = 0x05;
                ram_[0x25] = 0x0f;
                ram_[0x26] = 0x0b;
                break;
            case 0:
                ram_[0x2c] = 0x20;
                ram_[0x77] = 0x06;
                ram_[0x25] = 0x07;
                ram_[0x26] = 0x03;
                break;
            case 1:
                ram_[0x2c] = 0x31;
                ram_[0x77] = 0x05;
                ram_[0x25] = 0x0f;
                ram_[0x26] = 0x0b;
                break;
            case 2:
                ram_[0x2c] = 0x3c;
                ram_[0x77] = 0x04;
                ram_[0x25] = 0x13;
                ram_[0x26] = 0x0f;
                break;
            default: break;
        }
    } else {
        switch (dip) {
            case 3:
                ram_[0x2c] = 0x46;
                ram_[0x77] = 0x05;
                ram_[0x25] = 0x11;
                ram_[0x26] = 0x0e;
                break;
            case 0:
                ram_[0x2c] = 0x30;
                ram_[0x77] = 0x06;
                ram_[0x25] = 0x0b;
                ram_[0x26] = 0x03;
                break;
            case 1:
                ram_[0x2c] = 0x3a;
                ram_[0x77] = 0x05;
                ram_[0x25] = 0x0f;
                ram_[0x26] = 0x09;
                break;
            case 2:
                ram_[0x2c] = 0x4c;
                ram_[0x77] = 0x04;
                ram_[0x25] = 0x19;
                ram_[0x26] = 0x11;
                break;
            default: break;
        }
    }
}

void OpWolfCChip::clear_level_flags() {
    ram_[0x76] = 0;
    ram_[0x75] = 0;
    ram_[0x74] = 0;
    ram_[0x72] = 0;
    ram_[0x71] = 0;
    ram_[0x70] = 0;
    ram_[0x66] = 0;
    ram_[0x2b] = 0;
    ram_[0x30] = 0;
    ram_[0x31] = 0;
    ram_[0x32] = 0;
    ram_[0x27] = 0;
    c588_ = 0;
    c589_ = 0;
    c58a_ = 0;
}

void OpWolfCChip::complete_level_command() {
    const uint8_t level = ram_[0x1b];
    const uint8_t index = uint8_t(std::min<int>(level, 6));
    for (int i = 0; i < 0xcc; i++) {
        ram_[size_t(0x200 + i * 2 + 0)] = uint8_t(kLevelData[index][i] >> 8);
        ram_[size_t(0x200 + i * 2 + 1)] = uint8_t(kLevelData[index][i] & 0xff);
    }
    ram_[0] = 0;
    clear_level_flags();
    ram_[0x1a] = 0;
    ram_[0x7a] = 1;
    current_cmd_ = 0;
}

void OpWolfCChip::run_cycles(int cycles) {
    if (command_cycles_ < 0) return;
    command_cycles_ -= cycles;
    if (command_cycles_ > 0) return;
    command_cycles_ = -1;
    if (current_cmd_ == 0xf5) complete_level_command();
    current_cmd_ = 0;
}

void OpWolfCChip::update() {
    if (ram_[0x04] != last_04_) {
        int slot = -1;
        if ((ram_[0x04] & 1) != 0) slot = 0;
        if ((ram_[0x04] & 2) != 0) slot = 1;
        if (slot >= 0) {
            coins_[size_t(slot)] = uint8_t(coins_[size_t(slot)] + 1);
            if (coins_[size_t(slot)] >= coins_for_credit_[size_t(slot)]) {
                ram_[0x53] = uint8_t(ram_[0x53] + credits_for_coin_[size_t(slot)]);
                ram_[0x51] = 0x55;
                ram_[0x52] = 0x55;
                coins_[size_t(slot)] =
                    uint8_t(coins_[size_t(slot)] - coins_for_credit_[size_t(slot)]);
            }
        }
        if (ram_[0x53] > 9) ram_[0x53] = 9;
    }
    last_04_ = ram_[0x04];

    if (ram_[0x05] != last_05_) {
        if ((ram_[0x05] & 4) == 0) {
            ram_[0x53] = uint8_t(ram_[0x53] + 1);
            ram_[0x51] = 0x55;
            ram_[0x52] = 0x55;
        }
    }
    last_05_ = ram_[0x05];

    if (ram_[0x1b] == 6) {
        if (c58a_ == 0) {
            if (((ram_[0x72] & 0x7f) >= 8) && ram_[0x74] == 0 && ram_[0x1c] == 0 &&
                ram_[0x1d] == 0 && ram_[0x1f] == 0) {
                ram_[0x30] = 1;
                ram_[0x74] = 1;
                c58a_ = 1;
            }
        }
        if (ram_[0x1a] == 0x90) ram_[0x74] = 0;
        if (c58a_ != 0) {
            if (c589_ == 0 && ram_[0x27] == 0 && ram_[0x75] == 0 && ram_[0x1c] == 0 &&
                ram_[0x1d] == 0 && ram_[0x1e] == 0 && ram_[0x1f] == 0) {
                ram_[0x31] = 1;
                ram_[0x75] = 1;
                c589_ = 1;
            }
        }
        if (ram_[0x2b] == 1) {
            ram_[0x2b] = 0;
            if (ram_[0x30] == 1) {
                if (ram_[0x1a] != 0x90) ram_[0x1a] = uint8_t(ram_[0x1a] - 1);
            }
            if (ram_[0x72] == 9) {
                if (ram_[0x76] != 4) ram_[0x76] = 3;
            } else {
                c588_ = uint8_t(c588_ | 0x80);
                ram_[0x72] = c588_;
                c588_ = uint8_t(c588_ + 1);
                ram_[0x1a] = uint8_t(ram_[0x1a] - 3);
            }
        }
        if (ram_[0x76] == 0) {
            ram_[0x76] = 1;
            update_difficulty(1);
        }
    }

    if (ram_[0x34] < 2) {
        update_difficulty(0);
        clear_level_flags();
    }

    if (ram_[0x1c] == 0 && ram_[0x1d] == 0 && ram_[0x1e] == 0 && ram_[0x1f] == 0 &&
        ram_[0x20] == 0) {
        if (ram_[0x1b] == 6) {
            if (ram_[0x27] == 1) ram_[0x32] = 1;
        } else {
            ram_[0x32] = 1;
        }
    }

    if (ram_[0x0e] == 1) {
        ram_[0x0e] = 0xfd;
        ram_[0x61] = 0x04;
    }

    if (ram_[0x7a] == 0 && last_7a_ != 0 && current_cmd_ != 0xf5) {
        current_cmd_ = 0xf5;
        command_cycles_ = kCommandCycles;
    }
    last_7a_ = ram_[0x7a];

    if (ram_[0x7f] == 0x0a) {
        ram_[0xfe] = 0xf7;
        ram_[0xff] = 0x6e;
    }

    ram_[0x64] = 0;
    ram_[0x66] = 0;
}

