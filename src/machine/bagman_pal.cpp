void BagmanPal::reset() {
    for (uint8_t pin = 0; pin < 8; pin++) write(pin, 1);
    update();
}

void BagmanPal::write(uint8_t position, uint8_t value) {
    uint8_t line = uint8_t(position * 4);
    column_value_[line] = uint8_t(value & 1);
    column_value_[line + 1] = uint8_t(1 - (value & 1));
}

void BagmanPal::update() {
    for (int row = 0; row < 64; row++) {
        int row_offset = row * 32;
        uint8_t value = 1;  // prepare for AND
        for (int column = 0; column < 32; column++) {
            if (kFuseMap[row_offset + column] == 0) value &= column_value_[column];
        }
        and_map_[row] = value;
    }

    auto or_rows = [this](int first, int last) {
        uint8_t value = 0;  // prepare for OR
        for (int row = first; row <= last; row++) value |= and_map_[row];
        return value;
    };

    // I/O pin #19
    uint8_t value = or_rows(1, 7);
    if (and_map_[0] == 1) {
        column_value_[2] = uint8_t(1 - value);
        column_value_[3] = value;
        out_value_[0] = uint8_t(1 - value);
    } else {  // pin configured as input, so it does not drive an output
        column_value_[2] = 0;
        column_value_[3] = 1;
    }

    // Registered outputs, pins #18 (D1) down to #13 (D6)
    for (int output = 1; output <= 6; output++) {
        value = or_rows(output * 8, output * 8 + 7);
        column_value_[output * 4 + 2] = uint8_t(1 - value);
        column_value_[output * 4 + 3] = value;
        out_value_[output] = uint8_t(1 - value);
    }

    // I/O pin #12
    value = or_rows(57, 63);
    if (and_map_[56] == 1) {
        column_value_[30] = uint8_t(1 - value);
        column_value_[31] = value;
        out_value_[7] = uint8_t(1 - value);
    } else {
        column_value_[30] = 0;
        column_value_[31] = 1;
    }
}

// The Bagman schematics show this mapping of PAL outputs to data bits; /RD4 goes
// active whenever the CPU reads from memory address a000.
uint8_t BagmanPal::read() {
    update();
    return uint8_t(out_value_[6] + (out_value_[5] << 1) + (out_value_[4] << 2) +
                   (out_value_[3] << 3) + (out_value_[2] << 4) + (out_value_[1] << 5));
}

