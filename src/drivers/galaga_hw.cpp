void GalagaHw::draw_star(int set_a, int set_b, int scroll_x, int scroll_y, bool wrap_xy) {
    for (const auto& s : kStarSeeds) {
        if (s.set != set_a && s.set != set_b) continue;
        int x, y;
        if (wrap_xy) {
            y = (s.y + scroll_y) % 256 + 16;
            x = (112 + s.x + scroll_x) % 256;
        } else {
            y = (s.y + scroll_y) & 0xff;
            x = (s.x + scroll_x) & 0xff;
        }
        if (x < 0 || x >= screen_width_ || y < 0 || y >= screen_height_) continue;
        framebuffer_[size_t(y) * size_t(screen_width_) + size_t(x)] = palette_[size_t(32 + s.col)];
    }
}

void GalagaHw::render_galaga() {
    std::fill(framebuffer_.begin(), framebuffer_.end(), palette_[32 + kStarSeeds[0].col] & 0x00000000u);
    std::fill(framebuffer_.begin(), framebuffer_.end(), 0xff000000u);

    if ((star_control_[5] & 1) != 0) {
        const int set_a = star_control_[3] & 1;
        const int set_b = (star_control_[4] & 1) | 2;
        draw_star(set_a, set_b, scrollx_bg_, scrolly_bg_, true);
    }

    // Sprites ($8b80-$8bff attrs/colour, $9380-$93ff pos, $9b80-$9bff attrs2).
    for (int f = 0; f < 0x40; f++) {
        const uint8_t nchar = uint8_t(mem_[0x8b80 + f * 2] & 0x7f);
        const int color = (mem_[0x8b81 + f * 2] & 0x3f) << 2;
        int y = mem_[0x9381 + f * 2] - 40 + 0x100 * (mem_[0x9b81 + f * 2] & 3);
        int x = mem_[0x9380 + f * 2] - 16 - 1;
        const uint8_t atrib = mem_[0x9b80 + f * 2];
        const bool flip_x = (atrib & 2) != 0;
        const bool flip_y = (atrib & 1) != 0;
        // Only the 16x16 single-cell case is common in Galaga; larger
        // composite sprites reuse the same cell four times.
        const uint8_t* px = &sprites_rotated_[size_t(nchar & 0x7f) * 256];
        for (int sy = 0; sy < 16; sy++) {
            const int fy = y + sy;
            if (fy < 0 || fy >= screen_height_) continue;
            const int sy_src = flip_y ? 15 - sy : sy;
            for (int sx = 0; sx < 16; sx++) {
                const uint8_t p = px[sy_src * 16 + (flip_x ? 15 - sx : sx)];
                if (p == 0) continue;
                const int fx = x + sx;
                if (fx < 0 || fx >= screen_width_) continue;
                const uint8_t idx = tile_lut_[size_t(color + p) & 0xff];
                framebuffer_[size_t(fy) * size_t(screen_width_) + size_t(fx)] = palette_[idx & 0x5f];
            }
        }
    }

    // Char layer: 36x28 visible cells over a 32x64 tile RAM grid, drawn
    // straight from tile RAM every frame (no dirty tracking needed here).
    for (int x = 0; x <= 27; x++) {
        for (int y = 0; y <= 35; y++) {
            const int sx = 29 - x;
            const int sy = y - 2;
            int pos;
            if ((sy & 0x20) != 0) pos = sx + ((sy & 0x1f) << 5);
            else pos = sy + (sx << 5);
            if (pos < 0 || pos >= 0x400) continue;
            const int color = (mem_[0x8400 + pos] & 0x3f) << 2;
            const uint8_t nchar = mem_[0x8000 + pos];
            const uint8_t* px = &chars_rotated_[size_t(nchar) * 64];
            for (int py = 0; py < 8; py++) {
                const int fy = y * 8 + py;
                if (fy < 0 || fy >= screen_height_) continue;
                for (int pxi = 0; pxi < 8; pxi++) {
                    const uint8_t p = px[py * 8 + pxi];
                    if (p == 0) continue;
                    const int fx = x * 8 + pxi;
                    if (fx < 0 || fx >= screen_width_) continue;
                    const uint8_t idx = char_lut_[size_t(color + p) & 0xff];
                    framebuffer_[size_t(fy) * size_t(screen_width_) + size_t(fx)] = palette_[idx & 0x5f];
                }
            }
        }
    }
}

void GalagaHw::render_digdug() {}
void GalagaHw::render_bosconian() {}
void GalagaHw::render_xevious() {}

void GalagaHw::run_frame() {
    for (int line = 0; line < kScanlines; line++) {
        main_cpu_.run(main_cycles_per_line_);
        if (!sub_held_) sub_cpu_.run(main_cycles_per_line_);
        if (!sub2_held_) sub2_cpu_.run(main_cycles_per_line_);
        io51_.run(main_cycles_per_line_);
        io53_.run(main_cycles_per_line_);
        io54_.run(main_cycles_per_line_);

        if (line == 63 || line == 191) {
            if (sub2_nmi_) sub2_cpu_.set_nmi(IrqLine::Pulse);
        } else if (line == 223) {
            if (main_irq_) main_cpu_.set_irq(IrqLine::Assert);
            if (sub_irq_) sub_cpu_.set_irq(IrqLine::Assert);
            switch (game_) {
                case Game::Galaga: render_galaga(); break;
                case Game::DigDug: render_digdug(); break;
                case Game::Bosconian: render_bosconian(); break;
                case Game::Xevious:
                case Game::SuperXevious: render_xevious(); break;
            }
        }
    }
}

