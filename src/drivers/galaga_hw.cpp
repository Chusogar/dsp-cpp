uint8_t GalagaHw::main_read(uint16_t addr) {
    if (addr <= 0x3fff) return mem_[addr];
    if ((addr >= 0x8000 && addr <= 0x8bff) || (addr >= 0x9000 && addr <= 0x93ff) ||
        (addr >= 0x9800 && addr <= 0x9bff))
        return mem_[addr];
    if (addr >= 0x6800 && addr <= 0x6807) return dip_bits(uint8_t(addr & 7), uint8_t(addr & 7));
    if (addr >= 0x7000 && addr <= 0x70ff) return bridge_.data_read(uint8_t(addr & 0xff));
    if (addr == 0x7100) return bridge_.ctrl_read();
    return 0xff;
}

void GalagaHw::main_write(uint16_t addr, uint8_t value) {
    if (addr <= 0x3fff) return;  // ROM
    if (addr >= 0x6800 && addr <= 0x681f) {
        wsg_.write(addr & 0x1f, value);
        return;
    }
    if (addr >= 0x6820 && addr <= 0x6827) {
        latch_write(addr & 7, value);
        return;
    }
    if (addr >= 0x7000 && addr <= 0x70ff) {
        bridge_.data_write(uint8_t(addr & 0xff), value);
        return;
    }
    if (addr == 0x7100) {
        bridge_.ctrl_write(value);
        return;
    }
    if (addr >= 0x8000 && addr <= 0x87ff) {
        mem_[addr] = value;  // char RAM; redraw is unconditional per frame here
        return;
    }
    if ((addr >= 0x8800 && addr <= 0x8bff) || (addr >= 0x9000 && addr <= 0x93ff) ||
        (addr >= 0x9800 && addr <= 0x9bff)) {
        mem_[addr] = value;
        return;
    }
    if (addr >= 0xa000 && addr <= 0xa005) {
        star_control_[addr & 7] = value;
        return;
    }
    if (addr == 0xa007) {
        flip_screen_ = (value & 1) != 0;
        return;
    }
}

uint8_t GalagaHw::sub_read(uint16_t addr) {
    if (addr <= 0x3fff) return sub_rom_[addr];
    return main_read(addr);
}

uint8_t GalagaHw::sub2_read(uint16_t addr) {
    if (addr <= 0x3fff) return sub2_rom_[addr];
    return main_read(addr);
}

void GalagaHw::latch_write(int bit, uint8_t value) {
    const bool set = (value & 1) != 0;
    switch (bit) {
        case 0:
            main_irq_ = set;
            if (!set) main_cpu_.set_irq(IrqLine::Clear);
            break;
        case 1:
            sub_irq_ = set;
            if (!set) sub_cpu_.set_irq(IrqLine::Clear);
            break;
        case 2:
            sub2_nmi_ = !set;
            break;
        case 3: {
            const bool run = set;
            if (run && sub_held_) sub_cpu_.reset();
            if (run && sub2_held_) sub2_cpu_.reset();
            sub_held_ = !run;
            sub2_held_ = !run;
            break;
        }
        case 5:
            custom_mod_ = uint8_t((custom_mod_ & ~1) | (value & 1));
            break;
        case 6:
            custom_mod_ = uint8_t((custom_mod_ & ~2) | ((value & 1) << 1));
            break;
        case 7:
            custom_mod_ = uint8_t((custom_mod_ & ~4) | ((value & 1) << 2));
            break;
        default:
            break;
    }
}

uint8_t GalagaHw::dip_bits(uint8_t bit, uint8_t /*unused*/) const {
    const uint8_t b0 = uint8_t((dsw_b_ >> bit) & 1);
    const uint8_t b1 = uint8_t((dsw_a_ >> bit) & 1);
    return uint8_t(b0 | (b1 << 1));
}

void GalagaHw::set_dip_switch(int bank, uint8_t value) {
    if (bank == 0) dsw_a_ = value;
    if (bank == 1) dsw_b_ = value;
}

