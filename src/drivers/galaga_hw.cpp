std::vector<uint8_t> GalagaHw::rotate_cw(const GfxSet& src, int count, int size) {
    std::vector<uint8_t> out(size_t(count) * size_t(size) * size_t(size));
    for (int n = 0; n < count; n++) {
        const uint8_t* s = src.element(n);
        uint8_t* d = &out[size_t(n) * size_t(size) * size_t(size)];
        for (int row = 0; row < size; row++)
            for (int col = 0; col < size; col++)
                d[row * size + col] = s[(size - 1 - col) * size + row];
    }
    return out;
}

GalagaHw::GalagaHw(Game game)
    : game_(game),
      main_cpu_(kCpuClock),
      sub_cpu_(kCpuClock),
      sub2_cpu_(kCpuClock),
      wsg_(kCpuClock),
      io51_(kCpuClock),
      io53_(kCpuClock),
      io54_(kCpuClock) {
    if (game_ == Game::Bosconian) {
        screen_width_ = 285;
        screen_height_ = 224;
    } else {
        screen_width_ = 224;
        screen_height_ = 288;
    }
    framebuffer_.assign(size_t(screen_width_) * size_t(screen_height_), 0xff000000u);

    main_cpu_.set_memory_handlers([this](uint16_t a) { return main_read(a); },
                                  [this](uint16_t a, uint8_t v) { main_write(a, v); });
    sub_cpu_.set_memory_handlers([this](uint16_t a) { return sub_read(a); },
                                 [this](uint16_t a, uint8_t v) { main_write(a, v); });
    sub2_cpu_.set_memory_handlers([this](uint16_t a) { return sub2_read(a); },
                                  [this](uint16_t a, uint8_t v) { main_write(a, v); });
    main_cpu_.set_cycle_handler([this](int cycles) { on_main_cycles(cycles); });

    // 06xx slot 0 -> Namco51xx (coin/inputs), slot 3 -> Namco54xx (sound fx).
    // (Dig Dug instead wires slot 1 to Namco53xx; done in init() per game.)
    Namco06xx::Slot slot51;
    slot51.chip_select = [this](bool a) { io51_.set_chip_select(a); };
    slot51.set_rw = [this](bool r) { io51_.set_rw(r); };
    slot51.write = [this](uint8_t v) { io51_.write(v); };
    slot51.read = [this] { return io51_.read(); };
    bridge_.set_slot(0, slot51);

    Namco06xx::Slot slot54;
    slot54.chip_select = [this](bool a) { io54_.set_chip_select(a); };
    slot54.write = [this](uint8_t v) { io54_.write(v); };
    bridge_.set_slot(3, slot54);

    // In galaga_hw.pas, namco_06xx_nmi pulses the MAIN cpu's NMI line (not
    // the sub CPUs' - those are driven separately off the scanline counter).
    bridge_.set_nmi_callback([this] { main_cpu_.set_nmi(IrqLine::Pulse); });

    io51_.set_input(0, [this] { return uint8_t(in0_ & 0x0f); });
    io51_.set_input(1, [this] { return uint8_t(in0_ >> 4); });
    io51_.set_input(2, [this] { return uint8_t(in1_ & 0x0f); });
    io51_.set_input(3, [this] { return uint8_t(in1_ >> 4); });

    main_cycles_per_line_ = int(kCpuClock / uint32_t(kScanlines * kFramesPerSecond));
}

const char* GalagaHw::title() const {
    switch (game_) {
        case Game::Galaga: return "Galaga";
        case Game::DigDug: return "Dig Dug";
        case Game::Xevious: return "Xevious";
        case Game::SuperXevious: return "Super Xevious";
        case Game::Bosconian: return "Bosconian";
    }
    return "Galaga";
}

