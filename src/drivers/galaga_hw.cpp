// Namco/Galaxian-era resistor DAC weights, used across this whole hardware
// family for the base 32-colour hardware palette.
uint8_t rweight3(uint8_t bits) {
    return uint8_t(0x21 * (bits & 1) + 0x47 * ((bits >> 1) & 1) + 0x97 * ((bits >> 2) & 1));
}
uint32_t argb(uint8_t r, uint8_t g, uint8_t b) { return 0xff000000u | (uint32_t(r) << 16) | (uint32_t(g) << 8) | b; }

