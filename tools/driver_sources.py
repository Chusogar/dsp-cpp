#!/usr/bin/env python3
"""Works out which source files each driver needs and writes them to
ports/common/driver_sources.{json,cmake}, for the builds that cannot use the
dsp_lib static library trick (the microcontroller ports in ports/).

It reads the objects of a native build that has the dsp-<driver> targets
(cmake --build build --target dsp-drivers) and resolves symbols the way the
linker pulls members out of libdsp_lib.a: starting from the driver registry
compiled for that one driver, every object that defines a symbol still
undefined is added, until nothing more is needed.

    cmake -S . -B build && cmake --build build -j --target dsp-drivers
    python3 tools/driver_sources.py build

Run it again after adding a driver or moving code between files.
"""

import json
import os
import re
import subprocess
import sys

# Always part of a port: ROM loading, file access and the embedded media.
CORE = ["src/core/rom_loader.cpp", "src/core/fs_compat.cpp", "src/core/embedded_media.cpp"]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def symbols(obj):
    """(strong definitions, weak definitions, undefined) of an object file."""
    out = subprocess.run(["nm", "-P", obj], capture_output=True, text=True, check=True).stdout
    strong, weak, undef = set(), set(), set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) < 2:
            continue
        name, kind = parts[0], parts[1]
        if kind == "U":
            undef.add(name)
        elif kind in "WVu":
            weak.add(name)
        elif kind in "TDBRGSC" or kind == "i":
            strong.add(name)
    return strong, weak, undef


def library_objects(build):
    """{source path: object file} for dsp_lib and musashi."""
    objects = {}
    for lib in ("dsp_lib", "musashi"):
        base = os.path.join(build, "CMakeFiles", f"{lib}.dir")
        for root, _, names in os.walk(base):
            for name in names:
                if name.endswith(".o"):
                    full = os.path.join(root, name)
                    src = os.path.relpath(full, base)[:-2].replace(os.sep, "/")
                    objects[src] = full
    return objects


def closure(roots, pool, info):
    have, need = set(), set()
    chosen = []

    def add(src, obj):
        strong, weak, undef = info[obj]
        chosen.append(src)
        have.update(strong, weak)
        need.update(undef)

    for src, obj in roots:
        add(src, obj)
    strong_def, weak_def = {}, {}
    for src in sorted(pool):
        strong, weak, _ = info[pool[src]]
        for s in strong:
            strong_def.setdefault(s, src)
        for s in weak:
            weak_def.setdefault(s, src)
    while True:
        missing = sorted(s for s in need - have)
        added = False
        for s in missing:
            src = strong_def.get(s) or weak_def.get(s)
            if src is None or src in chosen:
                continue
            add(src, pool[src])
            added = True
            break
        if not added:
            break
    return chosen


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    build = sys.argv[1]
    with open(os.path.join(ROOT, "cmake", "drivers.cmake")) as f:
        text = f.read()
    groups = {}
    for group in ("ARCADE", "CONSOLES", "COMPUTERS"):
        m = re.search(r"set\(DSP_DRIVERS_%s\s+(.*?)\)" % group, text, re.S)
        groups[group.lower()] = m.group(1).split()
    pool = library_objects(build)
    info = {obj: symbols(obj) for obj in pool.values()}
    result = {}
    for group, drivers in groups.items():
        for driver in drivers:
            reg = os.path.join(build, "CMakeFiles", f"dsp-{driver}.dir", "src", "frontend",
                               "machine_registry.cpp.o")
            if not os.path.isfile(reg):
                sys.exit(f"driver_sources: {reg} missing: build the dsp-drivers target first")
            info[reg] = symbols(reg)
            roots = [("src/frontend/machine_registry.cpp", reg)] + [(c, pool[c]) for c in CORE]
            chosen = closure(roots, pool, info)
            sources = sorted(set(chosen) - {"src/frontend/machine_registry.cpp"} - set(CORE))
            result[driver] = {"group": group, "sources": sources}
            print(f"{driver:20s} {len(sources):3d} files")
    out_dir = os.path.join(ROOT, "ports", "common")
    os.makedirs(out_dir, exist_ok=True)
    data = {"core": CORE, "drivers": result}
    with open(os.path.join(out_dir, "driver_sources.json"), "w", newline="\n") as f:
        json.dump(data, f, indent=1, sort_keys=True)
        f.write("\n")
    with open(os.path.join(out_dir, "driver_sources.cmake"), "w", newline="\n") as f:
        f.write("# Generated by tools/driver_sources.py: do not edit.\n")
        f.write("# DSP_PORT_CORE_SOURCES and DSP_PORT_SOURCES_<driver>, relative to the repository.\n")
        f.write("set(DSP_PORT_CORE_SOURCES\n" + "".join(f"  {c}\n" for c in CORE) + ")\n")
        for driver in sorted(result):
            f.write(f"set(DSP_PORT_SOURCES_{driver}\n")
            f.write("".join(f"  {s}\n" for s in result[driver]["sources"]))
            f.write(")\n")
    print(f"driver_sources: wrote ports/common/driver_sources.json and .cmake ({len(result)} drivers)")


if __name__ == "__main__":
    main()
